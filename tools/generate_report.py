def percentile(data: List[float], p: float) -> float:
    if not data:
        return 0.0
    sorted_d = sorted(data)
    idx = (len(sorted_d) - 1) * p
    lower = math.floor(idx)
    upper = math.ceil(idx)
    if lower == upper:
        return sorted_d[int(idx)]
    d = idx - lower
    return sorted_d[lower] * (1.0 - d) + sorted_d[upper] * d


def build_svg_histogram(values: List[float], bins: int = 15, max_val: float = 15.0, width: int = 600, height: int = 240) -> str:
    if not values:
        return "<p class='empty-state'>No data available for distribution</p>"

    # Bin values
    bin_width = max_val / bins
    counts = [0] * bins
    for v in values:
        b = int(v / bin_width)
        if b < 0:
            b = 0
        elif b >= bins:
            b = bins - 1
        counts[b] += 1

    max_count = max(counts) if max(counts) > 0 else 1
    pad_left = 50
    pad_bottom = 35
    pad_top = 20
    pad_right = 20
    chart_w = width - pad_left - pad_right
    chart_h = height - pad_top - pad_bottom

    col_w = chart_w / bins
    svg_parts = [
        f'<svg viewBox="0 0 {width} {height}" class="chart-svg" xmlns="http://www.w3.org/2000/svg">',
        f'<line x1="{pad_left}" y1="{pad_top}" x2="{pad_left}" y2="{pad_top + chart_h}" stroke="#475569" stroke-width="1.5" />',
        f'<line x1="{pad_left}" y1="{pad_top + chart_h}" x2="{width - pad_right}" y2="{pad_top + chart_h}" stroke="#475569" stroke-width="1.5" />'
    ]

    # Gridlines
    for i in range(5):
        y_val = pad_top + chart_h - (i * chart_h / 4)
        count_val = int(i * max_count / 4)
        svg_parts.append(f'<line x1="{pad_left}" y1="{y_val}" x2="{width - pad_right}" y2="{y_val}" stroke="#334155" stroke-dasharray="3,3" />')
        svg_parts.append(f'<text x="{pad_left - 8}" y="{y_val + 4}" fill="#94a3b8" font-size="10" text-anchor="end">{count_val}</text>')

    # Target sweet spot highlight (2.0s to 4.5s)
    x_sweet_start = pad_left + (2.0 / max_val) * chart_w
    x_sweet_end = pad_left + (4.5 / max_val) * chart_w
    svg_parts.append(f'<rect x="{x_sweet_start}" y="{pad_top}" width="{x_sweet_end - x_sweet_start}" height="{chart_h}" fill="rgba(34, 197, 94, 0.12)" />')
    svg_parts.append(f'<text x="{(x_sweet_start + x_sweet_end)/2}" y="{pad_top + 14}" fill="#4ade80" font-size="10" font-weight="bold" text-anchor="middle">Target Sweet Spot (2-4.5s)</text>')

    # Instant kill zone highlight (< 1.0s)
    x_danger_end = pad_left + (1.0 / max_val) * chart_w
    svg_parts.append(f'<rect x="{pad_left}" y="{pad_top}" width="{x_danger_end - pad_left}" height="{chart_h}" fill="rgba(239, 68, 68, 0.15)" />')
    svg_parts.append(f'<text x="{(pad_left + x_danger_end)/2}" y="{pad_top + 28}" fill="#f87171" font-size="9" text-anchor="middle">Instant (&lt;1s)</text>')

    # Bars
    for i in range(bins):
        bar_h = (counts[i] / max_count) * chart_h
        bx = pad_left + i * col_w + 2
        by = pad_top + chart_h - bar_h
        bw = max(2, col_w - 4)

        t_mid = (i + 0.5) * bin_width
        fill_color = "#f87171" if t_mid < 1.0 else ("#22c55e" if 2.0 <= t_mid <= 4.5 else "#38bdf8")

        svg_parts.append(f'<rect x="{bx:.1f}" y="{by:.1f}" width="{bw:.1f}" height="{bar_h:.1f}" fill="{fill_color}" rx="2">')
        svg_parts.append(f'<title>Time: {i*bin_width:.1f}-{(i+1)*bin_width:.1f}s: {counts[i]} kills</title>')
        svg_parts.append('</rect>')

        if i % 3 == 0:
            svg_parts.append(f'<text x="{bx + bw/2:.1f}" y="{pad_top + chart_h + 16}" fill="#94a3b8" font-size="10" text-anchor="middle">{i*bin_width:.1f}s</text>')

    svg_parts.append('</svg>')
    return "".join(svg_parts)


def build_svg_weapon_bars(weapon_stats: Dict[str, Dict[str, float]], width: int = 600, height: int = 240) -> str:
    if not weapon_stats:
        return "<p class='empty-state'>No weapon damage recorded</p>"

    # Sort weapons by total damage descending
    sorted_w = sorted(weapon_stats.items(), key=lambda x: x[1]["total_dmg"] + x[1]["overkill"], reverse=True)[:8]
    if not sorted_w:
        return "<p class='empty-state'>No weapon data</p>"

    max_combined = max((w[1]["total_dmg"] + w[1]["overkill"]) for w in sorted_w)
    if max_combined <= 0:
        max_combined = 1.0

    pad_left = 130
    pad_right = 60
    pad_top = 20
    pad_bottom = 20
    row_h = (height - pad_top - pad_bottom) / len(sorted_w)
    chart_w = width - pad_left - pad_right

    svg_parts = [
        f'<svg viewBox="0 0 {width} {height}" class="chart-svg" xmlns="http://www.w3.org/2000/svg">'
    ]

    for idx, (name, data) in enumerate(sorted_w):
        y = pad_top + idx * row_h
        bar_y = y + 4
        bar_h = row_h - 10

        effective_w = (data["total_dmg"] / max_combined) * chart_w
        overkill_w = (data["overkill"] / max_combined) * chart_w

        label = name.replace("WEAPON_", "").replace("_", " ").title()
        if len(label) > 16:
            label = label[:14] + ".."

        svg_parts.append(f'<text x="{pad_left - 10}" y="{bar_y + bar_h/2 + 4}" fill="#cbd5e1" font-size="11" font-weight="500" text-anchor="end">{label}</text>')
        # Effective Damage Bar
        svg_parts.append(f'<rect x="{pad_left}" y="{bar_y}" width="{effective_w:.1f}" height="{bar_h}" fill="#38bdf8" rx="2">')
        svg_parts.append(f'<title>{name}: {data["total_dmg"]:.0f} dmg</title></rect>')
        # Overkill Bar
        svg_parts.append(f'<rect x="{pad_left + effective_w:.1f}" y="{bar_y}" width="{overkill_w:.1f}" height="{bar_h}" fill="#f43f5e" rx="2">')
        svg_parts.append(f'<title>{name} Overkill: {data["overkill"]:.0f}</title></rect>')

        total_dmg = data["total_dmg"] + data["overkill"]
        pct_overkill = (data["overkill"] / total_dmg * 100.0) if total_dmg > 0 else 0.0
        svg_parts.append(f'<text x="{pad_left + effective_w + overkill_w + 6:.1f}" y="{bar_y + bar_h/2 + 4}" fill="#94a3b8" font-size="10">{pct_overkill:.0f}% ovk</text>')

    svg_parts.append('</svg>')
    return "".join(svg_parts)


def build_svg_survival_curve(survival_series: Dict[str, List[Tuple[float, float]]], width: int = 600, height: int = 240) -> str:
    if not survival_series:
        return "<p class='empty-state'>No survival series data</p>"

    pad_left = 45
    pad_right = 130
    pad_top = 25
    pad_bottom = 35
    chart_w = width - pad_left - pad_right
    chart_h = height - pad_top - pad_bottom

    max_time = 0.0
    for series in survival_series.values():
        if series:
            max_time = max(max_time, max(pt[0] for pt in series))
    if max_time <= 0:
        max_time = 60.0

    svg_parts = [
        f'<svg viewBox="0 0 {width} {height}" class="chart-svg" xmlns="http://www.w3.org/2000/svg">',
        f'<line x1="{pad_left}" y1="{pad_top}" x2="{pad_left}" y2="{pad_top + chart_h}" stroke="#475569" stroke-width="1.5" />',
        f'<line x1="{pad_left}" y1="{pad_top + chart_h}" x2="{pad_left + chart_w}" y2="{pad_top + chart_h}" stroke="#475569" stroke-width="1.5" />'
    ]

    # Y-axis 0% to 100%
    for i in range(5):
        y_val = pad_top + chart_h - (i * chart_h / 4)
        pct_val = i * 25
        svg_parts.append(f'<line x1="{pad_left}" y1="{y_val}" x2="{pad_left + chart_w}" stroke="#334155" stroke-dasharray="3,3" />')
        svg_parts.append(f'<text x="{pad_left - 8}" y="{y_val + 4}" fill="#94a3b8" font-size="10" text-anchor="end">{pct_val}%</text>')

    # X-axis time marks
    for i in range(5):
        x_val = pad_left + (i * chart_w / 4)
        t_sec = i * max_time / 4
        svg_parts.append(f'<text x="{x_val}" y="{pad_top + chart_h + 16}" fill="#94a3b8" font-size="10" text-anchor="middle">{t_sec:.0f}s</text>')

    palette = ["#38bdf8", "#f59e0b", "#ec4899", "#10b981", "#8b5cf6"]
    color_idx = 0

    legend_y = pad_top + 10
    for label, points in survival_series.items():
        if not points:
            continue
        color = palette[color_idx % len(palette)]
        color_idx += 1

        path_d = []
        for i, (t, s_pct) in enumerate(points):
            px = pad_left + (t / max_time) * chart_w
            py = pad_top + chart_h - (s_pct / 100.0) * chart_h
            if i == 0:
                path_d.append(f"M {px:.1f} {py:.1f}")
            else:
                path_d.append(f"L {px:.1f} {py:.1f}")

        svg_parts.append(f'<path d="{" ".join(path_d)}" fill="none" stroke="{color}" stroke-width="2.5" />')
        # Legend entry
        svg_parts.append(f'<rect x="{pad_left + chart_w + 12}" y="{legend_y}" width="12" height="12" fill="{color}" rx="2" />')
        svg_parts.append(f'<text x="{pad_left + chart_w + 30}" y="{legend_y + 10}" fill="#e2e8f0" font-size="11">{label}</text>')
        legend_y += 20

    svg_parts.append('</svg>')
    return "".join(svg_parts)


def parse_telemetry(file_path: str) -> Dict[str, Any]:
    events = []
    with open(file_path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                events.append(json.loads(line))
            except json.JSONDecodeError:
                continue

    spawns = [e for e in events if e.get("event") == "spawn"]
    hits = [e for e in events if e.get("event") == "hit"]
    deaths = [e for e in events if e.get("event") == "death"]
    players = [e for e in events if e.get("event") == "player"]
    summaries = [e for e in events if e.get("event") == "summary"]

    # Fodder (Stage 1) TTKs
    ttk_s1 = [d["ttk"] for d in deaths if d.get("stage") == 1 and "ttk" in d]
    ttk_s2 = [d["ttk"] for d in deaths if d.get("stage") == 2 and "ttk" in d]
    ttk_s3 = [d["ttk"] for d in deaths if d.get("stage") >= 3 and "ttk" in d]

    instant_kills = sum(1 for t in ttk_s1 if t < 1.0)
    instant_kill_pct = (instant_kills / len(ttk_s1) * 100.0) if ttk_s1 else 0.0

    # Weapon breakdown
    weapon_stats = collections.defaultdict(lambda: {"hits": 0, "total_dmg": 0.0, "overkill": 0.0, "kills": 0})
    for h in hits:
        src = h.get("source", "UNKNOWN")
        weapon_stats[src]["hits"] += 1
        weapon_stats[src]["total_dmg"] += h.get("damage", 0.0)

    for d in deaths:
        killer = d.get("killer", "UNKNOWN")
        weapon_stats[killer]["kills"] += 1
        weapon_stats[killer]["overkill"] += d.get("overkill", 0.0)

    # Route breakdown
    route_stats = collections.defaultdict(lambda: {"spawns": 0, "kills": 0, "ttks": []})
    for s in spawns:
        r = s.get("route", "UNKNOWN")
        route_stats[r]["spawns"] += 1
    for d in deaths:
        r = d.get("route", "UNKNOWN")
        route_stats[r]["kills"] += 1
        if "ttk" in d:
            route_stats[r]["ttks"].append(d["ttk"])

    # Survival Curves per Archetype / Starter
    arch_runs = collections.defaultdict(list)
    for s in summaries:
        key = f"{s.get('starter', 'Unknown')} ({s.get('archetype', 'Unknown')})"
        arch_runs[key].append(s)

    survival_series = {}
    for group_name, runs in arch_runs.items():
        if not runs:
            continue
        max_run_time = max(r.get("time_survived", 0.0) for r in runs)
        if max_run_time <= 0:
            max_run_time = 60.0
        steps = 20
        pts = []
        for step in range(steps + 1):
            t = (step / steps) * max_run_time
            surviving = sum(1 for r in runs if r.get("time_survived", 0.0) >= t)
            pts.append((t, (surviving / len(runs)) * 100.0))
        survival_series[group_name] = pts

    return {
        "event_count": len(events),
        "spawns": spawns,
        "hits": hits,
        "deaths": deaths,
        "summaries": summaries,
        "ttk_s1": ttk_s1,
        "ttk_s2": ttk_s2,
        "ttk_s3": ttk_s3,
        "instant_kills": instant_kills,
        "instant_kill_pct": instant_kill_pct,
        "weapon_stats": dict(weapon_stats),
        "route_stats": dict(route_stats),
        "survival_series": survival_series
    }


