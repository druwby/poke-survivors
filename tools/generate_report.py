def main():
    parser = argparse.ArgumentParser(description="Big Data Telemetry Aggregator & HTML Balance Dashboard")
    parser.add_argument("--telemetry", "--input", "-i", dest="telemetry", default="test_telemetry.jsonl", help="Path to NDJSON/JSONL telemetry file")
    parser.add_argument("--output", "-o", default="balance_report.html", help="Path for generated HTML dashboard")
    args = parser.parse_args()

    if not os.path.exists(args.telemetry):
        print(f"Error: Telemetry file '{args.telemetry}' does not exist.", file=sys.stderr)
        sys.exit(1)

    data = parse_telemetry(args.telemetry)
    generate_html(data, args.output)


if __name__ == "__main__":
    main()
